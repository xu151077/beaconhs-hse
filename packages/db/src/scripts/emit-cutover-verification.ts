// Cutover verification SQL generator.
//
// The Phase 1.5 permission cutover needed two SQL artefacts: a post-migrate
// check and a rollback. Both were originally written with a hand-typed list of
// permission keys. That list drifted — it omitted 19 of the 93 catalogue keys —
// and the post-migrate check reported 35 false "stray key" findings.
//
// This module removes the second copy of the catalogue. Every permission key it
// emits is read from `PERMISSION_CATALOGUE` / `BUILTIN_ROLES`, so the SQL can
// never disagree with the schema. The rollback array is read from the database
// snapshot, which is the authority for "what the row used to be".
//
// Read-only: this module generates text. It never connects to a database.

import { BUILTIN_ROLES, PERMISSION_CATALOGUE } from '../schema'

/** A `roles` row captured before the cutover. */
export type RoleSnapshot = {
  id: string
  tenantId: string
  key: string
  isBuiltIn: boolean
  permissions: string[]
}

const asStrings = (values: readonly unknown[]): string[] => values as string[]

/** The authoritative permission catalogue, straight from the schema. */
export function catalogue(): string[] {
  return asStrings(PERMISSION_CATALOGUE)
}

/**
 * The permission names the cutover SQL asserts on by name, because they encode
 * the cutover decision itself: the target role must end up site-scoped for PPE,
 * not register-wide.
 *
 * These are the only permission-shaped strings the generator writes that are NOT
 * read from the catalogue, so they are the one place the generated SQL could
 * drift from the schema. They are therefore validated against it on every render.
 * If one of them were retired, the generated verification would otherwise keep
 * checking a key that no role can ever hold — permanently vacuous, while still
 * reporting success.
 */
export const CUTOVER_SPOT_CHECK_KEYS = ['ppe.read.self', 'ppe.read.site', 'ppe.read.all'] as const

function assertSpotCheckKeysExist(all: readonly string[]): void {
  const known = new Set(all)
  const missing = CUTOVER_SPOT_CHECK_KEYS.filter((key) => !known.has(key))
  if (missing.length > 0) {
    throw new Error(
      `cutover spot-check permissions are absent from PERMISSION_CATALOGUE: ${missing.join(', ')}. ` +
        'Restore them, or update CUTOVER_SPOT_CHECK_KEYS to match the cutover being verified — ' +
        'emitting SQL that checks a retired key would pass vacuously.',
    )
  }
}

/** The declared baseline of one built-in role. */
export function baselineFor(roleKey: string): string[] {
  const def = BUILTIN_ROLES[roleKey as keyof typeof BUILTIN_ROLES]
  if (!def) throw new Error(`Unknown built-in role: ${roleKey}`)
  return asStrings(def.permissions)
}

/** Render a string array as a single-quoted SQL literal list. */
function sqlLiteralList(values: readonly string[]): string {
  return values.map((value) => `'${value.replaceAll("'", "''")}'`).join(',')
}

/** Render a string array as a `jsonb` literal. */
function sqlJsonbLiteral(values: readonly string[]): string {
  return `'${JSON.stringify([...values].sort())}'::jsonb`
}

/**
 * The post-migrate verification SQL.
 *
 * The "no key outside the catalogue" check embeds the catalogue itself, derived
 * from the schema at generation time, instead of a literal that must be kept in
 * step by hand.
 */
export function renderPostMigrateSql(options: { tenantId: string; targetRoleId: string }): string {
  const { tenantId, targetRoleId } = options
  const all = catalogue()
  assertSpotCheckKeysExist(all)
  return `-- Phase 1.5 Permission Cutover v2 — POST-MIGRATE VERIFICATION
-- GENERATED by packages/db/src/scripts/emit-cutover-verification.ts — do not hand-edit.
--
-- Permission keys below are emitted from PERMISSION_CATALOGUE at generation time
-- (${all.length} keys). Regenerate rather than editing.

\\set ON_ERROR_STOP on
\\pset pager off

\\echo '=== [1] target role: site-scoped, NOT register-wide ==='
SELECT key,
       jsonb_array_length(permissions) AS n,
       permissions ? 'ppe.read.all'  AS ppe_all_must_be_false,
       permissions ? 'ppe.read.site' AS ppe_site_must_be_true
FROM roles
WHERE id = '${targetRoleId}'::uuid;
-- EXPECT: foreman | 36 | f | t

\\echo '=== [2] whole-tenant matrix ==='
SELECT key, is_built_in, jsonb_array_length(permissions) AS n,
       permissions ? 'ppe.read.self' AS ppe_self,
       permissions ? 'ppe.read.site' AS ppe_site,
       permissions ? 'ppe.read.all'  AS ppe_all
FROM roles WHERE tenant_id = '${tenantId}'::uuid
ORDER BY is_built_in DESC, key;

\\echo '=== [3] no role holds a key outside the catalogue (catalogue derived from schema) ==='
SELECT r.key, p AS stray_key
FROM roles r,
     LATERAL jsonb_array_elements_text(r.permissions) AS p
WHERE r.tenant_id = '${tenantId}'::uuid
  AND NOT (p = ANY (ARRAY[${sqlLiteralList(all)}]))
ORDER BY r.key, p;
-- EXPECT: 0 rows

\\echo '=== [4] each built-in role equals its declared baseline ==='
${baselineCheckSql(tenantId)};
-- EXPECT: 0 rows

\\echo '=== [5] custom roles are not built-in ==='
SELECT key, is_built_in, jsonb_array_length(permissions) AS n
FROM roles WHERE tenant_id = '${tenantId}'::uuid AND NOT is_built_in;

\\echo '=== [6] role assignments untouched ==='
SELECT count(*) AS assignments FROM role_assignments WHERE tenant_id = '${tenantId}'::uuid;

\\echo '=== [7] no new migration applied ==='
SELECT count(*) AS applied_migrations FROM drizzle.__drizzle_migrations;
`
}

/**
 * Assert every built-in role's live permissions equal its declared baseline.
 * The baselines come from `BUILTIN_ROLES`, so this cannot drift from the code.
 * Emits one row per difference, so "0 rows" means every role matches.
 */
function baselineCheckSql(tenantId: string): string {
  const branches = Object.keys(BUILTIN_ROLES).flatMap((key) => {
    const baseline = sqlJsonbLiteral(baselineFor(key))
    return [
      // present in the DB but not in the declared baseline
      `SELECT '${key}' AS role_key, 'extra_in_db' AS problem, p AS permission
  FROM roles r, LATERAL jsonb_array_elements_text(r.permissions) AS p
 WHERE r.tenant_id = '${tenantId}'::uuid
   AND r.key = '${key}'
   AND NOT (${baseline} ? p)`,
      // in the declared baseline but missing from the DB
      `SELECT '${key}', 'missing_from_db', v.value
  FROM jsonb_array_elements_text(${baseline}) AS v(value)
 WHERE EXISTS (SELECT 1 FROM roles r
                WHERE r.tenant_id = '${tenantId}'::uuid
                  AND r.key = '${key}')
   AND NOT EXISTS (SELECT 1 FROM roles r
                    WHERE r.tenant_id = '${tenantId}'::uuid
                      AND r.key = '${key}'
                      AND r.permissions ? v.value)`,
    ]
  })
  return branches.join('\nUNION ALL\n')
}

/**
 * The rollback SQL for one role row.
 *
 * The permission array comes from the caller-supplied snapshot, because the
 * purpose of a rollback is to restore that exact state — not to re-derive a
 * baseline from current code, which may have moved on.
 */
export function renderRollbackSql(row: RoleSnapshot): string {
  const expected = [...row.permissions].sort()
  return `-- Phase 1.5 Permission Cutover v2 — ROLLBACK (single role)
-- GENERATED by packages/db/src/scripts/emit-cutover-verification.ts — do not hand-edit.
--
-- Restores the pre-cutover permission array captured in the snapshot
-- (${expected.length} keys) for role "${row.key}". The array comes from the
-- snapshot, NOT from the catalogue: a rollback restores history, it does not
-- re-derive it.
--
-- ${row.isBuiltIn ? 'Built-in role.' : 'Custom role.'} Tenant ${row.tenantId}.

\\set ON_ERROR_STOP on
\\pset pager off

BEGIN;

UPDATE roles
SET permissions = ${sqlJsonbLiteral(expected)},
    updated_at = now()
WHERE id           = '${row.id}'::uuid
  AND tenant_id    = '${row.tenantId}'::uuid
  AND key          = '${row.key}'
  AND is_built_in  = ${row.isBuiltIn}
  AND jsonb_array_length(permissions) = ${expected.length}
  AND permissions  ? 'ppe.read.site'
  AND NOT (permissions ? 'ppe.read.all');

-- Expect UPDATE 1, then verify and COMMIT only if correct:
SELECT key,
       jsonb_array_length(permissions) AS n,
       permissions ? 'ppe.read.all'  AS ppe_all_should_be_true,
       permissions ? 'ppe.read.site' AS ppe_site_should_be_false
FROM roles
WHERE id = '${row.id}'::uuid;
-- EXPECT: ${row.key} | ${expected.length} | t | f

\\echo '--- exact set equality with the snapshot (must be 0 rows) ---'
-- '= ALL' would be vacuous here (text can never equal every element), so the
-- extra-in-db direction is expressed as NOT (… = ANY (…)). Both directions are
-- required: either alone would pass a half-applied rollback.
SELECT 'extra_in_db' AS problem, value
  FROM jsonb_array_elements_text(
         (SELECT permissions FROM roles WHERE id='${row.id}'::uuid))
 WHERE NOT (value = ANY (ARRAY[${sqlLiteralList(expected)}]))
UNION ALL
SELECT 'absent_but_in_snapshot', v.value
  FROM jsonb_array_elements_text(${sqlJsonbLiteral(expected)}) AS v(value)
 WHERE NOT EXISTS (SELECT 1 FROM roles r
                    WHERE r.id='${row.id}'::uuid AND r.permissions ? v.value);
-- EXPECT: 0 rows

COMMIT;
`
}
